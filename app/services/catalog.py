def get_category(slug):
    return next((item for item in CATEGORIES if item["slug"] == slug), None)


def get_subject(slug):
    return next((item for item in SUBJECTS if item["slug"] == slug), None)


def get_subjects_for_category(category_slug):
    return [
        item for item in SUBJECTS
        if item["category_slug"] == category_slug
    ]


def search_subjects(query, limit=10):
    query = query.strip().lower()

    if not query:
        return []

    results = []
    for subject in SUBJECTS:
        searchable = (
            subject["name"] + " " +
            subject["summary"] + " " +
            subject["category_name"]
        ).lower()

        if query in searchable:
            results.append(subject)

    return results[:limit]
